"""Repro bundles and GitHub-issue drafts for a flagged comparison.

A bundle is the scenario file, one baseline trajectory, one candidate
trajectory, both diffs, a manifest, and an issue draft a person can paste.
"""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from harnesswatch.compare import Comparison
from harnesswatch.scenario import Scenario
from harnesswatch.trajectory import ToolCall, Trajectory


def write_bundles(
    comparisons: list[Comparison],
    scenarios: dict[str, Scenario],
    scenario_dir: Path,
    output_dir: Path,
) -> None:
    for comparison in comparisons:
        if not comparison.alert:
            continue
        bundle = output_dir / comparison.harness / comparison.scenario_id
        bundle.mkdir(parents=True, exist_ok=True)
        scenario = scenarios[comparison.scenario_id]
        source = scenario_dir / f"{scenario.id}.yaml"
        shutil.copyfile(source, bundle / "scenario.yaml")
        baseline = comparison.representative("baseline")
        candidate = comparison.representative("candidate")
        _copy_run(baseline.transcript_path, bundle, "baseline")
        _copy_run(candidate.transcript_path, bundle, "candidate")
        draft = render_issue(comparison, scenario)
        (bundle / "ISSUE.md").write_text(draft, encoding="utf-8")
        manifest = {
            "harness": comparison.harness,
            "scenario": comparison.scenario_id,
            "baseline_version": comparison.baseline_version,
            "candidate_version": comparison.candidate_version,
            "baseline_run": baseline.transcript_path.name,
            "candidate_run": candidate.transcript_path.name,
            "baseline_passes": comparison.baseline_passes,
            "baseline_n": comparison.baseline_n,
            "candidate_passes": comparison.candidate_passes,
            "candidate_n": comparison.candidate_n,
            "fisher_p_worse": comparison.fisher_p,
            "reasons": comparison.reasons,
            "note": (
                "Generated from recorded fixtures. This draft describes the "
                "fixture pair, not a live vendor release, unless you produced "
                "the trajectories with harnesswatch run."
            ),
        }
        (bundle / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


def render_issue(comparison: Comparison, scenario: Scenario) -> str:
    baseline = comparison.representative("baseline")
    candidate = comparison.representative("candidate")
    base_steps = _step_lines(baseline.trajectory)
    cand_steps = _step_lines(candidate.trajectory)
    references = "\n".join(f"- {url}" for url in scenario.references) or "- (none)"
    reasons = "\n".join(f"- {reason}" for reason in comparison.reasons)
    return f"""# Behavioral regression: {scenario.id} on {comparison.harness} {comparison.baseline_version} → {comparison.candidate_version}

## Summary

{scenario.summary}

Pass rate moved from {_pct(comparison.baseline_rate)} ({comparison.baseline_passes}/{comparison.baseline_n}) to {_pct(comparison.candidate_rate)} ({comparison.candidate_passes}/{comparison.candidate_n}).

{reasons}

## Scenario

- Harness: `{comparison.harness}`
- Category: {scenario.category}
- Prompt: {scenario.prompt}

## Trajectory contrast

Baseline `{comparison.baseline_version}` run {baseline.index:02d} (pass={str(baseline.trajectory_passed).lower()}):

{base_steps}

Candidate `{comparison.candidate_version}` run {candidate.index:02d} (pass={str(candidate.trajectory_passed).lower()}):

{cand_steps}

Final reply, baseline:

> { _quote(baseline.trajectory.final_reply) }

Final reply, candidate:

> { _quote(candidate.trajectory.final_reply) }

## Reproduce

```bash
harnesswatch run --scenario scenarios/{scenario.id}.yaml --harness {comparison.harness}
```

That command is a live CLI run. It needs an API key (`ANTHROPIC_API_KEY` or `CODEX_API_KEY`), not a consumer subscription. The bundle next to this draft contains `scenario.yaml`, `baseline.jsonl`, `candidate.jsonl`, and both diffs.

## Related public reports

{references}

## Scope

This draft was generated by HarnessWatch so a regression can be filed with the scenario and both trajectories attached. Numbers above come from the runs in this bundle. They are not a claim that a particular upstream release was reproduced unless those runs were live CLI sessions.
"""


def _copy_run(transcript: Path, bundle: Path, role: str) -> None:
    shutil.copyfile(transcript, bundle / f"{role}.jsonl")
    diff = transcript.with_suffix(".diff")
    if diff.exists():
        shutil.copyfile(diff, bundle / f"{role}.diff")


def _step_lines(trajectory: Trajectory) -> str:
    if not trajectory.tool_calls:
        return "1. (no tool calls)"
    lines = []
    for index, call in enumerate(trajectory.tool_calls, start=1):
        lines.append(f"{index}. {_format_call(call)}")
    if trajectory.permission_prompts:
        lines.append(f"- permission prompts: {trajectory.permission_prompts}")
    if trajectory.approval_policy:
        lines.append(f"- approval_policy: {trajectory.approval_policy}")
    usage = trajectory.usage
    lines.append(
        "- tokens: "
        f"input={usage.input_tokens} cache_read={usage.cache_read_tokens} "
        f"cache_creation={usage.cache_creation_tokens} output={usage.output_tokens} "
        f"cache_hit_rate={usage.cache_hit_rate:.3f}"
    )
    return "\n".join(lines)


def _format_call(call: ToolCall) -> str:
    if call.command:
        preview = call.command.replace("\n", " ")
        if len(preview) > 180:
            preview = preview[:177] + "..."
        return f"{call.name} `{preview}`"
    if call.paths:
        return f"{call.name} {call.paths[0]}"
    return call.name


def _quote(text: str) -> str:
    cleaned = " ".join(text.split())
    if not cleaned:
        return "(empty)"
    if len(cleaned) > 400:
        return cleaned[:397] + "..."
    return cleaned


def _pct(rate: float) -> str:
    return f"{rate * 100:.1f}%"
